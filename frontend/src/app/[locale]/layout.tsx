import type { Metadata } from "next";
import { Inter, Noto_Sans_JP } from "next/font/google";
import "./globals.css";
import MyProvider from "./components/provider";
import { NextIntlClientProvider } from "next-intl";
import { getMessages } from "next-intl/server";
import { notFound } from "next/navigation";
import { routing } from "@/i18n/routing";
import { Toaster } from "@/components/ui/toaster";

const notoSansJP400 = Noto_Sans_JP({
  weight: "400",
  display: "swap",
  preload: false,
});

export const metadata: Metadata = {
  title: `${process.env.NEXT_PUBLIC_APP_NAME}`,
  description: "Generated by create next app",
};


export default async function RootLayout({
  children,
  params
}: {
  children: React.ReactNode;
  params: Promise<{ locale: string }>;
}) {
  const { locale: raw } = await params;

  // 実行時・型の両方で "en" | "ja" に狭める（不正値は 'en' にフォールバック）
  const allowed = ["en", "ja"] as const;
  type Locale = typeof allowed[number];
  const locale: Locale = (allowed as readonly string[]).includes(raw) ? (raw as Locale) : "en";


  // Providing all messages to the client
  // side is the easiest way to get started
  const messages = await getMessages();

  return (
    <html lang={locale}>
      <head>
        <link rel="icon" href="/braingram/favicon.ico" />
      </head>
      <body className={notoSansJP400.className}>
        <NextIntlClientProvider locale={locale} messages={messages}>
          <MyProvider>{children}</MyProvider>
        </NextIntlClientProvider>
        <Toaster />
      </body>
    </html>
  );
}
